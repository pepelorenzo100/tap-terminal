<?php

/*
|--------------------------------------------------------------------------
| TAP TERMINAL
| PRUEBAS CRUD DE PRODUCTOS
|--------------------------------------------------------------------------
|
| Archivo:
| tests/Feature/ProductTest.php
|
| Tipo:
| BACKEND - Laravel / PHP / PHPUnit
|
| Responsabilidad:
|
| Verificar directamente el funcionamiento de la API
| REST de productos.
|
| Las pruebas comprueban:
|
| 1. Crear producto.
| 2. Listar productos.
| 3. Consultar un producto.
| 4. Actualizar un producto.
| 5. Eliminar un producto.
| 6. Validar datos incorrectos.
|
|--------------------------------------------------------------------------
*/

namespace Tests\Feature;

/*
|--------------------------------------------------------------------------
| TEST CASE
|--------------------------------------------------------------------------
|
| Clase base proporcionada por Laravel para realizar
| pruebas HTTP y de aplicación.
|
*/

use App\Models\Product;
/*
|--------------------------------------------------------------------------
| PRODUCT MODEL
|--------------------------------------------------------------------------
|
| Modelo utilizado para verificar los documentos
| almacenados en MongoDB.
|
*/

use Tests\TestCase;

/**
 * ============================================================
 * PRODUCT TEST
 * ============================================================
 *
 * Pruebas funcionales de la API REST de productos.
 *
 * Flujo comprobado:
 *
 * HTTP
 *   ↓
 * ProductController
 *   ↓
 * Product
 *   ↓
 * MongoDB
 *
 * ============================================================
 */
class ProductTest extends TestCase
{
    /**
     * ========================================================
     * CREAR PRODUCTO
     * ========================================================
     *
     * Verifica:
     *
     * POST /api/products
     *
     * Debe:
     *
     * - aceptar los datos válidos;
     * - responder HTTP 201;
     * - generar automáticamente un código;
     * - devolver el producto creado.
     *
     * ========================================================
     */
    public function test_can_create_product(): void
    {

        /*
        |--------------------------------------------------------------------------
        | DATOS DEL PRODUCTO
        |--------------------------------------------------------------------------
        */

        $data = [

            'name' => 'Producto de prueba',

            'brand' => 'TAP',

            'price' => 250.00,

        ];

        /*
        |--------------------------------------------------------------------------
        | REALIZAR PETICIÓN POST
        |--------------------------------------------------------------------------
        */

        $response = $this->postJson(

            '/api/products',

            $data

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR RESPUESTA HTTP
        |--------------------------------------------------------------------------
        |
        | 201 significa:
        |
        | "Created"
        |
        */

        $response->assertStatus(201);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR ESTRUCTURA
        |--------------------------------------------------------------------------
        */

        $response->assertJsonStructure([

            'id',

            'name',

            'brand',

            'price',

            'code',

            'created_at',

            'updated_at',

        ]);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR DATOS
        |--------------------------------------------------------------------------
        */

        $response->assertJsonPath(

            'name',

            'Producto de prueba'

        );

        $response->assertJsonPath(

            'brand',

            'TAP'

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR CÓDIGO AUTOMÁTICO
        |--------------------------------------------------------------------------
        */

        $this->assertStringStartsWith(

            'PROD-',

            $response->json('code')

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR EXISTENCIA EN BASE DE DATOS
        |--------------------------------------------------------------------------
        */

        $this->assertDatabaseHas(

            'products',

            [

                'name' => 'Producto de prueba',

                'brand' => 'TAP',

            ]

        );

    }

    /**
     * ========================================================
     * LISTAR PRODUCTOS
     * ========================================================
     *
     * Verifica:
     *
     * GET /api/products
     *
     * ========================================================
     */
    public function test_can_list_products(): void
    {

        /*
        |--------------------------------------------------------------------------
        | CREAR PRODUCTO DE PRUEBA
        |--------------------------------------------------------------------------
        */

        Product::create([

            'name' => 'Producto listado',

            'brand' => 'TAP',

            'price' => 100.00,

        ]);

        /*
        |--------------------------------------------------------------------------
        | REALIZAR PETICIÓN GET
        |--------------------------------------------------------------------------
        */

        $response = $this->getJson(

            '/api/products'

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR RESPUESTA
        |--------------------------------------------------------------------------
        */

        $response->assertStatus(200);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR QUE SEA UN ARREGLO JSON
        |--------------------------------------------------------------------------
        */

        $response->assertJsonIsArray();

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR PRODUCTO
        |--------------------------------------------------------------------------
        */

        $response->assertJsonFragment([

            'name' => 'Producto listado',

            'brand' => 'TAP',

        ]);

    }

    /**
     * ========================================================
     * MOSTRAR PRODUCTO
     * ========================================================
     *
     * Verifica:
     *
     * GET /api/products/{id}
     *
     * ========================================================
     */
    public function test_can_show_product(): void
    {

        /*
        |--------------------------------------------------------------------------
        | CREAR PRODUCTO
        |--------------------------------------------------------------------------
        */

        $product = Product::create([

            'name' => 'Producto individual',

            'brand' => 'TAP',

            'price' => 300.00,

        ]);

        /*
        |--------------------------------------------------------------------------
        | CONSULTAR PRODUCTO
        |--------------------------------------------------------------------------
        */

        $response = $this->getJson(

            '/api/products/'.$product->id

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR RESPUESTA
        |--------------------------------------------------------------------------
        */

        $response->assertStatus(200);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR DATOS
        |--------------------------------------------------------------------------
        */

        $response->assertJson([

            'id' => (string) $product->id,

            'name' => 'Producto individual',

            'brand' => 'TAP',

        ]);

    }

    /**
     * ========================================================
     * ACTUALIZAR PRODUCTO
     * ========================================================
     *
     * Verifica:
     *
     * PUT /api/products/{id}
     *
     * ========================================================
     */
    public function test_can_update_product(): void
    {

        /*
        |--------------------------------------------------------------------------
        | CREAR PRODUCTO
        |--------------------------------------------------------------------------
        */

        $product = Product::create([

            'name' => 'Producto original',

            'brand' => 'TAP',

            'price' => 200.00,

        ]);

        /*
        |--------------------------------------------------------------------------
        | GUARDAR CÓDIGO ORIGINAL
        |--------------------------------------------------------------------------
        |
        | El código NO debe cambiar al actualizar.
        |
        */

        $originalCode = $product->code;

        /*
        |--------------------------------------------------------------------------
        | DATOS NUEVOS
        |--------------------------------------------------------------------------
        */

        $data = [

            'name' => 'Producto actualizado',

            'brand' => 'TAP',

            'price' => 450.00,

        ];

        /*
        |--------------------------------------------------------------------------
        | REALIZAR PETICIÓN PUT
        |--------------------------------------------------------------------------
        */

        $response = $this->putJson(

            '/api/products/'.$product->id,

            $data

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR RESPUESTA
        |--------------------------------------------------------------------------
        */

        $response->assertStatus(200);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR DATOS ACTUALIZADOS
        |--------------------------------------------------------------------------
        */

        $response->assertJsonPath(

            'name',

            'Producto actualizado'

        );

        $response->assertJsonPath(

            'brand',

            'TAP'

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR QUE EL CÓDIGO NO CAMBIÓ
        |--------------------------------------------------------------------------
        */

        $response->assertJsonPath(

            'code',

            $originalCode

        );

    }

    /**
     * ========================================================
     * ELIMINAR PRODUCTO
     * ========================================================
     *
     * Verifica:
     *
     * DELETE /api/products/{id}
     *
     * ========================================================
     */
    public function test_can_delete_product(): void
    {

        /*
        |--------------------------------------------------------------------------
        | CREAR PRODUCTO
        |--------------------------------------------------------------------------
        */

        $product = Product::create([

            'name' => 'Producto para eliminar',

            'brand' => 'TAP',

            'price' => 150.00,

        ]);

        /*
        |--------------------------------------------------------------------------
        | REALIZAR PETICIÓN DELETE
        |--------------------------------------------------------------------------
        */

        $response = $this->deleteJson(

            '/api/products/'.$product->id

        );

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR RESPUESTA
        |--------------------------------------------------------------------------
        */

        $response->assertStatus(200);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR MENSAJE
        |--------------------------------------------------------------------------
        */

        $response->assertJson([

            'message' => 'Producto eliminado correctamente.',

        ]);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR QUE YA NO EXISTA
        |--------------------------------------------------------------------------
        */

        $this->assertDatabaseMissing(

            'products',

            [

                '_id' => $product->id,

            ]

        );

    }

    /**
     * ========================================================
     * VALIDAR DATOS
     * ========================================================
     *
     * Verifica que Laravel rechace un producto
     * con datos inválidos.
     *
     * ========================================================
     */
    public function test_cannot_create_product_with_invalid_data(): void
    {

        /*
        |--------------------------------------------------------------------------
        | DATOS INVÁLIDOS
        |--------------------------------------------------------------------------
        */

        $data = [

            'name' => '',

            'brand' => '',

            'price' => 5000,

        ];

        /*
        |--------------------------------------------------------------------------
        | REALIZAR PETICIÓN
        |--------------------------------------------------------------------------
        */

        $response = $this->postJson(

            '/api/products',

            $data

        );

        /*
        |--------------------------------------------------------------------------
        | HTTP 422
        |--------------------------------------------------------------------------
        |
        | Laravel utiliza 422 cuando los datos
        | no cumplen las reglas de validación.
        |
        */

        $response->assertStatus(422);

        /*
        |--------------------------------------------------------------------------
        | VERIFICAR ERRORES
        |--------------------------------------------------------------------------
        */

        $response->assertJsonValidationErrors([

            'name',

            'brand',

            'price',

        ]);

    }
}
